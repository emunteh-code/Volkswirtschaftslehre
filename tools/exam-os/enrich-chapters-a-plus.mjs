#!/usr/bin/env node
/** Generate aPlusSupplement.js for modules with hand-authored chapters.js */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const slugs = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ['makro2', 'makro1', 'recht', 'finanzwirtschaft', 'jahresabschluss', 'internationale-wirtschaftsbeziehungen', 'statistik', 'mikro2', 'mikro1'];

function countSections(theorie) {
  const s = typeof theorie === 'string' ? theorie : (Array.isArray(theorie) ? theorie.join('') : '');
  return (s.match(/section-block/g) || []).length + (s.match(/section\(/g) || []).length;
}

function drillTask(title, warnTitle, warnBody) {
  return {
    text: `Klausurfalle (${title}): ${warnTitle} — erkläre den Fehler und die korrekte Vorgehensweise.`,
    steps: [
      { text: `Typischer Fehler: ${warnTitle}.`, eq: null },
      { text: warnBody, eq: null },
      { text: 'Formuliere die Prüfreihenfolge für eine ähnliche Aufgabe.', eq: null }
    ],
    result: warnBody,
    sourceStatus: 'platform-added-drill'
  };
}

function extractWarnBoxes(theorie) {
  const s = typeof theorie === 'string' ? theorie : '';
  const re = /<strong>([^<]+):<\/strong>\s*([^<]+)/g;
  const out = [];
  let m;
  while ((m = re.exec(s)) && out.length < 2) {
    out.push({ title: m[1].trim(), body: m[2].trim() });
  }
  return out;
}

for (const slug of slugs) {
  const chaptersPath = path.join(repoRoot, slug, 'js/data/chapters.js');
  if (!fs.existsSync(chaptersPath)) continue;

  const { CONTENT, CHAPTERS } = await import(`file://${chaptersPath}`);
  const supplement = {};

  for (const ch of CHAPTERS) {
    const entry = CONTENT[ch.id];
    if (!entry) continue;
    const sec = countSections(entry.theorie);
    const tasks = entry.aufgaben?.length || 0;
    const formeln = entry.formeln?.length || 0;
    const needTasks = Math.max(0, 3 - tasks);
    const needFormeln = Math.max(0, 3 - formeln);
    const needSections = Math.max(0, 4 - sec);
    if (!needTasks && !needFormeln && !needSections) continue;

    supplement[ch.id] = {};
    const warns = extractWarnBoxes(entry.theorie);

    if (needTasks) {
      const extra = [];
      if (warns[0]) extra.push(drillTask(ch.title, warns[0].title, warns[0].body));
      if (warns[1] && extra.length < needTasks) extra.push(drillTask(ch.title, warns[1].title, warns[1].body));
      while (extra.length < needTasks) {
        extra.push({
          text: `Mechanismus-Check (${ch.title}): Nenne die zentrale Gleichung oder Identität dieses Blocks und erkläre ihre Klausurrolle in drei Schritten.`,
          steps: [
            { text: entry.motivation || 'Motivation aus dem Konzeptblock.', eq: null },
            { text: 'Ordne Daten, Parameter und Gleichgewichtsgrößen zu.', eq: null },
            { text: 'Benenne eine typische Fehlinterpretation.', eq: null }
          ],
          result: 'Saubere Zuordnung der Größen ist Voraussetzung für korrekte Rechnung und Graphik.',
          sourceStatus: 'platform-added-drill'
        });
      }
      supplement[ch.id].aufgaben = extra.slice(0, needTasks);
    }

    if (needFormeln && entry.formeln?.length) {
      const f0 = entry.formeln[0];
      supplement[ch.id].formeln = [{
        label: `${f0.label} (Merksatz)`,
        eq: f0.eq,
        desc: f0.desc || 'Kernrelation des Konzepts.',
        variables: f0.variables || {},
        sourceStatus: 'source-distilled'
      }].slice(0, needFormeln);
    }
  }

  const outFile = path.join(repoRoot, slug, 'js/data/aPlusSupplement.js');
  fs.writeFileSync(
    outFile,
    `// Generated by tools/exam-os/enrich-chapters-a-plus.mjs\nexport const A_PLUS_SUPPLEMENT = ${JSON.stringify(supplement, null, 2)};\n`
  );
  console.log(`${slug}: ${Object.keys(supplement).length} concepts in supplement`);

  let src = fs.readFileSync(chaptersPath, 'utf8');
  if (!src.includes('A_PLUS_SUPPLEMENT')) {
    if (slug === 'makro2') {
      src = src.replace(
        "import { COURSEWORK_TASKS } from './courseworkTasks.js';",
        "import { COURSEWORK_TASKS } from './courseworkTasks.js';\nimport { A_PLUS_SUPPLEMENT } from './aPlusSupplement.js';"
      );
      src = src.replace(
        'const practice = (id, extras = []) => [\n  ...extras.map(cloneTask),\n  ...((COURSEWORK_TASKS[id] || []).map(cloneTask))\n];',
        'const practice = (id, extras = []) => [\n  ...extras.map(cloneTask),\n  ...((A_PLUS_SUPPLEMENT[id]?.aufgaben || []).map(cloneTask)),\n  ...((COURSEWORK_TASKS[id] || []).map(cloneTask))\n];'
      );
    } else if (src.includes('const task = ')) {
      src = src.replace(
        /^(import[^\n]+\n)+/m,
        (m) => `${m}import { A_PLUS_SUPPLEMENT } from './aPlusSupplement.js';\n\nfunction mergeAPlusEntry(id, base) {\n  const sup = A_PLUS_SUPPLEMENT[id] || {};\n  return {\n    ...base,\n    formeln: [...(base.formeln || []), ...(sup.formeln || [])],\n    aufgaben: [...(base.aufgaben || []), ...(sup.aufgaben || [])]\n  };\n}\n`
      );
      console.log(`${slug}: manual merge may be needed for CONTENT structure`);
    }
    fs.writeFileSync(chaptersPath, src);
  }
}
